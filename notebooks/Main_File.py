    "    # Inspection / test outcomes\n",
    "    ([\"started working\", \"went away\", \"working ok\", \"worked fine\", \"ran fine\"], \"Inspection/Test Only\"),\n",
    "\n",
    "    # Mechanical tighten/adjust\n",
    "    ([\"came loose\", \"took apart\"], \"Tighten/Adjust\"),\n",
    "]\n",
    "\n",
    "UNIGRAM_MAP = [\n",
    "    # Installation / replacement\n",
